function buildFallbackRecord(username: string): MockProfileRecord {
  const base = mockProfileRecords.neutralobserver;
  const handle = username.replace(/^@/, "").toLowerCase();
  const name = titleCaseFromHandle(handle) || "Neutral Observer";

  return {
    ...base,
    user: {
      ...base.user,
      id: `fallback-${handle}`,
      name,
      username: handle || base.user.username,
      description:
        handle && handle !== base.user.username
          ? `Public affairs account for @${handle}. Using the default neutral analysis fixture until a named mock profile is selected.`
          : base.user.description,
    },
  };
}

function getMockProfileRecord(username: string): MockProfileRecord {
  const handle = username.replace(/^@/, "").toLowerCase();
  return mockProfileRecords[handle] ?? buildFallbackRecord(handle);
}

export function getProfile(username: string): Profile {
  return toProfile(getMockProfileRecord(username).user);
}

export function getProfileAnalysisContext(username: string): ProfileAnalysisContext {
  const record = getMockProfileRecord(username);

  return {
    user: record.user,
    posts: record.posts,
    profile: toProfile(record.user),
    activityStats: record.activityStats,
    topics: record.topics,
    activityTimeline: record.activityTimeline,
    politicalVerdict: record.politicalVerdict,
  };
}
